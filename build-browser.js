// Regenerate after changing engine.js, fortune.js or fortunes.json. No dependencies.
import { readFile, writeFile } from 'node:fs/promises';
const read = name => readFile(new URL(name, import.meta.url), 'utf8');
const [engine, app, data] = await Promise.all(['engine.js','fortune.js','fortunes.json'].map(read));
const output = '// Generated by node build-browser.js. Edit sources, then rebuild.\n' +
  '(() => {\n"use strict";\n' +
  `const LOCAL_FORTUNES = ${JSON.stringify(JSON.parse(data))};\n` +
  engine.replace(/^export /gm, '') + '\n' +
  app.replace(/^import .* from '\.\/engine\.js';\r?\n/, '') + '\n})();\n';
await writeFile(new URL('browser.js', import.meta.url), output, 'utf8');
console.log('browser.js generated with the complete offline database.');
